def display_note(lang: str, value: str | None) -> str:
    """把存储的备注转成当前语言的显示形态。

    **只动完整标签与分隔符**：按「；/;」切出的完整片段若是默认 canonical，换成
    当前语言显示名；其余片段与空白原样保留。不做全文/子串替换，不 trim、不折叠、
    不补尾 —— 真正的格式化只在用户显式保存时（jobs.labels.normalize_note）。
    """
    if not value:
        return ""
    sep = note_sep(lang)
    parts = re.split(r"([；;])", str(value))
    for i in range(0, len(parts), 2):
        seg = parts[i]
        tag = seg.strip()
        if not tag:
            continue
        display = note_tag_display(lang, tag)
        if display != tag and tag in seg:
            parts[i] = seg.replace(tag, display, 1)
    gap = note_gap(lang)
    for i in range(1, len(parts), 2):
        nxt = parts[i + 1] if i + 1 < len(parts) else ""
        parts[i] = sep + (gap if gap and nxt and not nxt[0].isspace() else "")
    return "".join(parts)


def host_strings(lang: str) -> dict[str, str]:
    """侧栏 / 对比页宿主界面的文案（保留 sidebar. 前缀）。只在授权了侧栏或对比页时注入
    window.__HOST_I18N__，所以未启用插件的页面字节不变。"""
    return {k: t(lang, k) for k in STRINGS[DEFAULT_LANG] if k.startswith("sidebar.")}


def js_strings(lang: str) -> dict[str, str]:
    """前端脚本用的那部分文案（去掉 js. 前缀），注入为 window.__I18N__。"""
    keys = [k for k in STRINGS[DEFAULT_LANG] if k.startswith(("plugin.", "js.", "set.", "field.", "value.", "theme.", "filter.", "lang.", "run.", "ago.", "qualification.", "state.", "card.", "location.", "sel."))]
    return {k: t(lang, k) for k in keys}
